/**
 * 친구끼리 「지금 접속 중」을 어디까지 보여줄지.
 *
 *   'off'   아무것도 안 보여준다
 *   'count' 몇 명인지만 보여준다 — 누구인지는 안 나간다
 *   'list'  이름과 마지막 신호까지 (처음 만들었던 모양)
 *
 * 'count'에서는 사람별 online·secondsAgo가 **아예 응답에 실리지 않는다**. 숫자는
 * 따로 세어(onlineFriendCount) 그 값만 내보낸다 — 화면에서만 가리고 값을 보내면
 * 개발자 도구로 그대로 읽히기 때문이다.
 *
 * 숫자만으로도 좁혀질 수 있다는 것은 알고 쓴다: 친구가 한 명인데 「1명」이 뜨면 그건
 * 이름을 부른 것과 같다. 열두어 명짜리 모임이라 감수하기로 한 값이고, 걸리면 여기서
 * 'off'로 내리면 된다.
 *
 * 신호는 모드와 무관하게 그대로 쌓인다 — 관리자 화면의 접속 기록은 계속 돌아간다.
 */
export type PresenceMode = 'off' | 'count' | 'list';
export const FRIEND_PRESENCE: PresenceMode = 'count';
