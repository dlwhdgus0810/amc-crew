/**
 * 후기 규칙 — 서버와 화면이 함께 쓴다.
 *
 * 여기에는 DB를 부르는 것이 없다. 화면에서 lib/db/reviews.ts를 불러오면 drizzle까지
 * 브라우저 번들에 딸려 온다 (lib/ratings.ts·lib/photos.ts와 같은 이유).
 */

/**
 * 한 줄의 길이.
 *
 * 「한줄 후기」라는 말대로 두 줄쯤에서 끊는다. 길게 쓸 이야기는 모임 댓글이 이미
 * 받고 있고, 모아보기는 한 화면에 여러 사람의 목소리가 보여야 뜻이 있다.
 */
export const REVIEW_MAX = 200;

/**
 * 한 줄의 **최소** 길이.
 *
 * 「재밌었어요」 한 마디는 쓴 사람에게도 읽는 사람에게도 남는 것이 없다. 서른 자면
 * 무엇이 어땠는지 한 가지는 적게 되는 길이다 — 「코트가 생각보다 넓어서 처음엔
 * 헤맸는데 다들 기다려줘서 금방 붙었어요」가 서른여덟 자다.
 *
 * **이미 올라온 후기는 건드리지 않는다.** 지난 것을 지우거나 다시 쓰게 하는 규칙이
 * 아니라 앞으로 쓸 것에만 거는 문턱이라, 예전 후기는 그대로 보이고 그대로 남는다.
 * 다만 그 짧은 후기를 **고치려고** 하면 그때는 서른 자를 채워야 한다 — 새로 저장하는
 * 것은 새 글이기 때문이다. 지우는 것은 길이와 상관없이 언제든 된다.
 */
export const REVIEW_MIN = 30;

/** 모아보기에 싣는 줄 수 — 이 저장소에는 무한 스크롤이 없다 (전부 자른다) */
export const REVIEW_FEED_LIMIT = 30;
